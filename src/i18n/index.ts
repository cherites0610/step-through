export function explain(
  lang: Locale,
  e: { key: string; params?: Record<string, string | number> },
): string {
  const tpl = messages[lang][e.key] ?? e.key;
  return tpl.replace(/\{(\w+)\}/g, (_, k: string) => String(e.params?.[k] ?? `{${k}}`));
}
